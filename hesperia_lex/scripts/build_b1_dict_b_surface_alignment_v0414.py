#!/usr/bin/env python3
"""Build B1 side->family Dict B from real surface map source only."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

CANONICAL_JSON = "B1_SIDE_TO_FAMILY_v0_4_1_4.json"
CANONICAL_SHA = "B1_SIDE_TO_FAMILY_v0_4_1_4.sha256"
AUDIT_REPORT = Path("assets/v0414/b1_surface_alignment_audit_report.txt")
# Full taxonomy surface: 12 areas × 24 families × 250 hex × 6 sides (sphere_rag.invariant_catalog.TOTAL_SIDES)
try:
    from sphere_rag.invariant_catalog import TOTAL_SIDES as TOTAL_SIDES_EXPECTED
except ImportError:
    TOTAL_SIDES_EXPECTED = 432_000
SIDE_COUNT_MEANING = "surface subset produced by v0.4.0 embedding pass (sides with at least one placed token or role)"


def get_expected_surface_sha(repo_root: Path) -> str | None:
    """Read expected surface_map sha from canonical record or .sha256 file. None if not locked."""
    canonical = repo_root / "assets/v040/CANONICAL_SURFACE_V040.txt"
    sha_file = repo_root / "assets/v040/surface_map_v040.json.sha256"
    if canonical.exists():
        for line in canonical.read_text(encoding="utf-8").splitlines():
            if line.startswith("surface_map_sha256:"):
                val = line.split(":", 1)[1].strip()
                if val and val != "UNSET":
                    return val
    if sha_file.exists():
        val = sha_file.read_text(encoding="utf-8").split()[0]
        if val and val != "UNSET":
            return val
    return None


def discover_surface_sources(repo_root: Path) -> list[Path]:
    preferred = repo_root / "assets/v040/surface_map_v040.json"
    found: list[Path] = []
    if preferred.exists():
        found.append(preferred)
    patterns = ["*surface_map*.json", "*side_map*.json", "*72k*.json"]
    candidates: set[Path] = set()
    for pattern in patterns:
        for p in repo_root.rglob(pattern):
            if ".git" in p.parts or "node_modules" in p.parts:
                continue
            candidates.add(p)
    for p in sorted(candidates):
        if p != preferred:
            found.append(p)
    return found


def extract_side_to_family(surface_data: object) -> dict[str, int]:
    out: dict[str, int] = {}
    if isinstance(surface_data, dict):
        if "sides" in surface_data and isinstance(surface_data["sides"], list):
            iterable = surface_data["sides"]
        else:
            iterable = None

        if iterable is not None:
            for row in iterable:
                if not isinstance(row, dict):
                    continue
                side_id = row.get("side_id")
                family = row.get("familyGlobal")
                if family is None and isinstance(side_id, int):
                    family = side_id // 1500
                if isinstance(side_id, int) and isinstance(family, int):
                    if 0 <= family <= 287:
                        out[str(side_id)] = family
        else:
            int_keyed = all(re.fullmatch(r"\d+", str(k)) for k in surface_data.keys())
            if int_keyed:
                for k, v in surface_data.items():
                    side_id = int(k)
                    if isinstance(v, dict) and isinstance(v.get("familyGlobal"), int):
                        family = v["familyGlobal"]
                    else:
                        family = side_id // 1500
                    if 0 <= family <= 287:
                        out[str(side_id)] = family
    return dict(sorted(out.items(), key=lambda kv: int(kv[0])))


def fail_with_report(message: str, tried: list[Path], report_path: Path) -> int:
    lines = [
        "B1 Surface Alignment Audit Report v0.4.1.4",
        "status: HARD_FAIL_MISSING_SURFACE_SOURCE",
        f"reason: {message}",
        "tried_sources:",
    ]
    lines.extend(f"- {p}" for p in tried)
    lines.extend(
        [
            "required_dependency:",
            "- Commit a real surface map artifact (e.g., assets/v040/surface_map_v040.json) generated by the v0.4.0 surface pipeline.",
            "- Re-run this builder after the artifact exists.",
            "note: builder intentionally does not synthesize or mock surface data.",
        ]
    )
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("ERROR:", message, file=sys.stderr)
    for p in tried:
        print(f"tried: {p}", file=sys.stderr)
    print(f"wrote {report_path}")
    return 2


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo-root", type=Path, default=Path("."))
    parser.add_argument("--out-dir", type=Path, default=Path("hesperia_lex/frozen"))
    parser.add_argument("--report", type=Path, default=AUDIT_REPORT)
    args = parser.parse_args()

    repo_root = args.repo_root.resolve()
    sources = discover_surface_sources(repo_root)

    if not sources:
        attempted = [repo_root / "assets/v040/surface_map_v040.json"]
        return fail_with_report("No committed surface source found.", attempted, args.report)

    surface_path = sources[0]
    # Checksum gate: if canonical/expected sha is recorded, current file must match (surface is immutable).
    expected_sha = get_expected_surface_sha(repo_root)
    if expected_sha:
        actual_sha = hashlib.sha256(surface_path.read_bytes()).hexdigest()
        if actual_sha != expected_sha:
            args.report.parent.mkdir(parents=True, exist_ok=True)
            args.report.write_text(
                "\n".join([
                    "B1 Surface Alignment Audit Report v0.4.1.4",
                    "status: HARD_FAIL_SURFACE_CHECKSUM_MISMATCH",
                    "reason: surface_map_v040.json checksum does not match canonical/expected; surface is locked.",
                    f"expected_sha256: {expected_sha}",
                    f"actual_sha256: {actual_sha}",
                    "required: Do not rebuild surface silently. Any hash change = version bump.",
                ]) + "\n",
                encoding="utf-8",
            )
            print("ERROR: surface checksum mismatches expected; surface is immutable.", file=sys.stderr)
            print(f"expected={expected_sha} actual={actual_sha}", file=sys.stderr)
            return 1
    data = json.loads(surface_path.read_text(encoding="utf-8"))
    side_to_family = extract_side_to_family(data)
    if not side_to_family:
        return fail_with_report(
            f"Surface source found but schema unsupported for side/family extraction: {surface_path}",
            sources,
            args.report,
        )

    args.out_dir.mkdir(parents=True, exist_ok=True)
    out_json = args.out_dir / CANONICAL_JSON
    out_sha = args.out_dir / CANONICAL_SHA
    out_json.write_text(json.dumps(side_to_family, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    digest = hashlib.sha256(out_json.read_bytes()).hexdigest()
    out_sha.write_text(f"{digest}  {out_json.name}\n", encoding="utf-8")

    side_count = len(side_to_family)
    coverage_ratio = side_count / TOTAL_SIDES_EXPECTED if TOTAL_SIDES_EXPECTED else 0.0
    lines = [
        "B1 Surface Alignment Audit Report v0.4.1.4",
        "status: OK",
        f"surface_source: {surface_path}",
        f"side_count: {side_count}",
        f"side_count_meaning: {SIDE_COUNT_MEANING}",
        f"total_sides_expected: {TOTAL_SIDES_EXPECTED}",
        f"coverage_ratio: {side_count}/{TOTAL_SIDES_EXPECTED} = {coverage_ratio:.6f}",
        f"output_json: {out_json}",
        f"output_sha256: {out_sha}",
    ]
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out_json}")
    print(f"wrote {out_sha}")
    print(f"wrote {args.report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
